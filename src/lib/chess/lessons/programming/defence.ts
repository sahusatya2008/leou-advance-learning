const STAGE = "Defence in Code";

const ESCAPE_LOOP = `def move(game):
    # legal_moves() already excludes anything that leaves our king in check,
    # so a move that still leaves the king safe has escaped.
    for m in game.legal_moves():
        after = game.apply(m)
        if after is not None and not after.in_check():
            return m
    return game.legal_moves()[0]
`;

const CAPTURE_CHECKER = (target: string) => `def move(game):
    # take the piece that is giving check
    for m in game.legal_moves():
        if m[2:4] == ${JSON.stringify(target)}:
            return m
    return game.legal_moves()[0]
`;

