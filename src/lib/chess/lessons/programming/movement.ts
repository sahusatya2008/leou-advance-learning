const STAGE = "Movement & Attacks";

const CHECK_LOOP = `def move(game):
    for m in game.legal_moves():
        after = game.apply(m)
        if after is not None and after.in_check():
            return m
    return game.legal_moves()[0]
`;

const CAPTURE_LOOP = (target: string) => `def move(game):
    for m in game.legal_moves():
        if m[2:4] == ${JSON.stringify(target)}:
            return m
    return game.legal_moves()[0]
`;

