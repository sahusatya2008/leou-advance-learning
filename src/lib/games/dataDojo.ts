/**
 * DATA DOJO — compute-the-value challenges (the `output` kind).
 *
 * There is no world here: the student writes a `solve(s)` that receives one
 * string and returns a value, and the harness runs every test case in a single
 * sandbox pass. The values are always compared as trimmed strings, so the same
 * level grades identically in Python, JavaScript and Java.
 *
 * The problems climb a real curriculum — arithmetic, loops, strings, lists,
 * recursion, searching and sorting — so a student can warm up on `n * 2` and end
 * up writing a prime sieve, all inside the same neon cabinet.
 */

